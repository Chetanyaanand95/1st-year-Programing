// c) For Loop
// Aim:

// To print numbers from 1 to 5 using for loop.

// Algorithm:
// Start
// Initialize i = 1
// Check condition i ≤ 5
// If true, display i
// Increment i by 1
// Repeat until condition becomes false
// Stop

#include <iostream>
using namespace std;

int main() {
    for(int i = 1; i <= 5; i++)
        cout << i << " ";

    return 0;
}